export const NAME_REGEX = /^(?!.*[\r\n])(?=.*[A-Za-z])[A-Za-z\s]{1,32}$/;

export const PASSWORD_REGEX =
  /^(?=.*[A-Z])(?=.*[a-z])(?=.*[0-9])(?=.*[^A-Za-z0-9\s]).{8,32}$/;

export const EMAIL_REGEX =
  /^((?![-_+.])(?!.*\.\.)[a-zA-Z0-9-_+.]{1,64}(?<![-_+.]))@((?!-)(?!.*--)[-a-zA-Z0-9]{1,63}(?<!-))\.((?!\.)(?!.*\.\.)[.a-zA-Z]{2,63}(?<!\.))$/;
